"""Generates the lake position resources used by getClosesLake and the lake menu
from scripts/lake_borders.json.

Writes one border resource per lake, the circle index around each lake's border
points and the matching array of resource ids, all in the same lake order, and
the lake choices of the lake menu.
Run from the repository root after changing scripts/lake_borders.json:
    python scripts/generate_lake_resources.py
"""

import json
import math
from pathlib import Path

JSON_DATA = Path("resources/jsonData")
BORDERS = JSON_DATA / "lakeBorders"
# Rounds circle values up to stay a safe lower bound after rounding
DECIMALS = 6


def round_up(value):
    return math.ceil(value * 10**DECIMALS) / 10**DECIMALS


def circle(points):
    center = [sum(p[0] for p in points) / len(points), sum(p[1] for p in points) / len(points)]
    radius = max(math.dist(center, p) for p in points)
    return [round(center[0], DECIMALS), round(center[1], DECIMALS), round_up(radius + 10**-DECIMALS)]


def main():
    lakes = json.loads(Path("scripts/lake_borders.json").read_text(encoding="utf8"))
    BORDERS.mkdir(parents=True, exist_ok=True)
    for old in BORDERS.glob("*.json"):
        old.unlink()

    circles = []
    for name, points in lakes.items():
        border = {"name": name, "points": points}
        (BORDERS / f"{name}.json").write_text(json.dumps(border, separators=(",", ":")) + "\n")
        circles += circle(points)
    (JSON_DATA / "lakeCircles.json").write_text(json.dumps(circles, separators=(",", ":")) + "\n")
    # Name and circle center of each lake for the lake menu, sorted by name
    choices = sorted([name, *circle(points)[:2]] for name, points in lakes.items())
    (JSON_DATA / "lakeChoices.json").write_text(json.dumps(choices, separators=(",", ":")) + "\n")

    xml = ["<!-- Generated by scripts/generate_lake_resources.py -->", "<jsonDataResources>"]
    xml.append('    <jsonData id="LakeCircles" filename="lakeCircles.json" />')
    xml.append('    <jsonData id="LakeChoices" filename="lakeChoices.json" />')
    xml += [f'    <jsonData id="LakeBorder_{n}" filename="lakeBorders/{n}.json" />' for n in lakes]
    xml.append("</jsonDataResources>")
    (JSON_DATA / "jsonData.xml").write_text("\n".join(xml) + "\n")

    code = [
        "// Generated by scripts/generate_lake_resources.py",
        "import Toybox.Lang;",
        "",
        "//! Border resource of each lake, in the order of the circles in Rez.JsonData.LakeCircles",
        "function lakeBorderResources() as Array<ResourceId> {",
        "    return [",
    ]
    code += [f"        Rez.JsonData.LakeBorder_{n}," for n in lakes]
    code += ["    ];", "}", ""]
    Path("source/LakeBorderResources.mc").write_text("\n".join(code), newline="\n")


if __name__ == "__main__":
    main()
